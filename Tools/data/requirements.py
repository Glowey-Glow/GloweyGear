"""Builds Data/Requirements.lua: the equippable items that ask for a profession skill.

The game has no call that says "this item needs Engineering 150" without reading tooltip text, and
an Auction House row is weighed before its tooltip exists. The client's own item table says it for
every item: ItemSparse.RequiredSkill (a skill line) and RequiredSkillRank. This script lists the
equippable items that have one, as itemID -> { skill line, rank }.

    python -I Tools/data/requirements.py <folder with ItemSparse.csv and SkillLine.csv> <build>

The two tables are the client's, as CSV from wago.tools
(https://wago.tools/db2/ItemSparse/csv?build=<build>, .../SkillLine/csv?build=<build>). Facts of
the game only; nothing from another addon. A skill line that is a branch of a profession
(SkillLine.ParentSkillLineID, e.g. 2941 under Engineering 202) is written as its profession: that
is the line the character's profession list names. Run again after a game build that adds items.
"""
import csv
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(os.path.dirname(os.path.dirname(HERE)), "Data", "Requirements.lua")
# InventoryType values that are not worn or wielded: none, bag, ammo, quiver.
NOT_GEAR = {"0", "18", "24", "27"}


def rows(folder, name):
    with open(os.path.join(folder, name + ".csv"), encoding="utf-8", newline="") as handle:
        return list(csv.DictReader(handle))


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    folder, build = sys.argv[1], sys.argv[2]
    parent, names = {}, {}
    for r in rows(folder, "SkillLine"):
        line = int(r["ID"])
        names[line] = r["DisplayName_lang"]
        up = int(r["ParentSkillLineID"] or 0)
        if up:
            parent[line] = up
    found = {}
    for r in rows(folder, "ItemSparse"):
        line = int(r["RequiredSkill"] or 0)
        if not line or r["InventoryType"] in NOT_GEAR:
            continue
        line = parent.get(line, line)
        found[int(r["ID"])] = (line, int(r["RequiredSkillRank"] or 0), r["Display_lang"])
    lines = sorted({v[0] for v in found.values()})
    out = [
        "-- Generated by Tools/data/requirements.py from the game client's ItemSparse and SkillLine tables",
        "-- (build %s, read through wago.tools); do not edit: run the script again." % build,
        "-- The equippable items that ask for a profession skill: itemID -> { skill line, rank }.",
        "-- Skill lines: " + ", ".join("%d %s" % (l, names.get(l, "?")) for l in lines) + ".",
        "local _, ns = ...",
        "ns.ItemSkill = {",
    ]
    for item in sorted(found):
        line, rank, name = found[item]
        out.append("\t[%d] = { %d, %d },   -- %s" % (item, line, rank, name))
    out.append("}")
    with open(OUT, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(out) + "\n")
    print("%d items, %d skill lines -> %s" % (len(found), len(lines), OUT))


main()
